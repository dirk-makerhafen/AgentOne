REFLECTION_PROMPT = """SELF-IMPROVEMENT REFLECTION REPORT

Your sole objective is to observe and report raw diagnostic telemetry (what went wrong and why) so a specialized downstream agent 
can engineer improvements based on your report. Do not summarize session data or facts. If this session is some short or default task that 
needs no meaningful self reflection, just return "no self improvement reflections to report" as your final_result

Report observable facts from this session that a later improvement process could use: WHAT happened, with concrete evidence, plus a cause classification only. 
Do NOT guess fixes — classify observations only. If unsure of the cause, use "unclear". If an area had no issues, say so explicitly. Do NOT invent problems.
The actual improvements to the system prompt, instructions, and harness source code will be generated by a smarter LLM with access to the full codebase, internal prompts,
and harness internals. Your role is to faithfully report observations so that smarter process can act on them. 

Look for:
- mistakes or incorrect decisions
- inefficient or unnecessarily complicated approaches, loops, retries
- repeated failure patterns, repeated questions, information you had to rediscover
- cases where you should have asked, checked, verified, or acted differently
- cases where you misunderstood the task or user intent
- missing capabilities or weaknesses in the agent harness
- missing, unclear, or wrong instructions
- behavior suggesting a system-prompt or instruction gap (describe the behavior, do NOT draft the rule)
- workflows the harness could have automated or triggered earlier (describe what happened, do NOT design the mechanism)
- information you repeatedly had to rediscover that could be provided automatically
- successful approaches that should be preserved and codified (describe them, do NOT write the instruction text)
- Cognitive/Logic Loops: Where did you get stuck, repeat yourself, or retry failing solutions?
- Communication Flaws: Over-apologizing, verbosity, or ignoring user hints/constraints?
- Tool/Execution Missteps: Did you call tools inefficiently, use wrong arguments, or fail to verify an output before presenting it?
- Successful Strategy Shifts: Did you pivot your approach mid-session in a way that unlocked progress? What triggered that pivot?
- Technical Bottlenecks: e.g., API timeouts, token limits reached, format errors
- Logic Errors/Loops: e.g., "Got stuck in a 4-turn loop trying to refactor X", "Misunderstood constraint Y in turn 14"
- Crucial Facts Discovered: List any vital pieces of information learned about the environment, user codebase, or user preferences that MUST NOT be forgotten

For each observation, provide exactly:
- WHAT: what happened (1-2 lines, with concrete evidence — quote, tool name, file path, or message reference)
- WHY: why you think it happened. (reasoning mistake / missing or unclear instruction / system-prompt gap / harness or tool limitation / missing capability / unclear)
- WHERE: where any improvement can be made (system_prompt / instructions / harness / tooling / memory-knowledge / unclear)

Requirements:
- Be concise but comprehensive. Prioritize high-impact, repeated issues over minor stylistic points.
- If an area had no issues, say so explicitly.
- Do NOT modify anything yourself. Do not write a new system prompt. Report only.
- Focus on observations that would help a smarter LLM generate meaningful improvements later.

Do not modify files, do not write code, and do not suggest specific prompt modifications yourself. Output only the full report via final_result tool.


"""


def _resolve_anchor(kwargs: dict) -> Any:
    """Return the message an after-hook invocation should fork from.

    ``session_end`` returns ``last_message_pk``; the ``compact_turn`` chain
    returns ``message`` (the compaction marker). Both arrive here already
    resolved to model instances by the call-argument resolver.
    """
    pk = kwargs.get("last_message_pk")
    if isinstance(pk, int):
        found = Message.objects.filter(pk=pk).first()
        if found is not None:
            return found
    msg = kwargs.get("message")
    if isinstance(msg, Message):
        return msg
    if isinstance(msg, int):
        return Message.objects.filter(pk=msg).first()
    if isinstance(msg, dict) and msg.get("pk") is not None:
        return Message.objects.filter(pk=msg["pk"]).first()
    return None


def reflect_session(
    _session: Session,
    **kwargs: Any,
):
    """Fork the session and inject the reflection prompt as a user message.

    Invoked as a detached ``after:`` intercept hook on the ``session_end``
    task, so ``kwargs`` is that task's result. The fork is anchored at the
    returned ``last_message_pk`` (fixed at dispatch, so an async end cannot
    move the range the fork sees), pinned to never auto-compact, and only
    ``final_result`` is advertised.
    """
    anchor = _resolve_anchor(kwargs)
    if anchor is None:
        # No anchor available (unknown invocation, or the anchor row
        # vanished): do not guess from the session tail, which may have
        # moved under us. Skip instead of forking on a stale range.
        return None

    child_session = _session.fork(
        name=f"p{_session.model.pk}:reflection:{datetime.now().strftime('%Y.%m.%d-%H:%M:%S')}",
        description=f"Reflection fork for {_session.name}",
        session_type=SessionType.SUBTASK_HOOK,
        group_key="internal:reflection",
        anchor=anchor,
        auto_compact_max_tokens=0,
        auto_compact_idle_seconds=0,
        tool_call_allowlist=["final_result"],
    )

    # Trigger the fork's turn; the returned call is the report source the
    # parent-side ingest auto-awaits.
    reflection_result = child_session.add_user_message(
        [
            {
                "role": MessageRole.USER,
                "message_type": MessageType.SYSTEM_NOTICE,
                "content": "<SYSTEM NOTICE> You are in a forked copy of this session created for post-mortem analysis.\n"
                " - DO NOT continue the original task.\n"
                " - DO NOT modify any files or call any tools except final_result.\n"
                " - Your only job is to OBSERVE this session and REPORT what you notice.\n"
                "</SYSTEM NOTICE>",
            },
            {
                "role": MessageRole.ASSISTANT,
                "message_type": MessageType.ASSISTANT_MESSAGE,
                "content": "Confirmed, awaiting instructions for analysis.",
            },
            {
                "role": MessageRole.USER,
                "message_type": MessageType.SYSTEM_NOTICE,
                "message": REFLECTION_PROMPT,
            },
        ]
    )
    # Parent-side ingest: runs in the observed session once the fork's turn
    # resolves (``reflection_result`` is that call, auto-awaited), inserting
    # the report after the session-end anchor.
    ingest_task = _session.get_task("ingest_reflection_result")
    if ingest_task is None:
        return None
    return ingest_task.delay(
        anchor_message=anchor, reflection_result=reflection_result
    )


def _extract_report_text(result: Any) -> str:
    """Extract plain report text from the reflection fork's final result.

    The fork only advertises ``final_result`` (tool_call_allowlist), so the
    text arrives as that tool call's ``content`` argument (content-addressed
    for large bodies) — mirrors ``ingest_compaction._extract_summary_text``.
    """
    if isinstance(result, Message):
        text = ""
        for part in result.parts.order_by("pk"):
            if part.type == MessagePartType.MESSAGE:
                content = part.content.get() if part.content else None
                text += str(content) if content else ""
            elif (
                part.type == MessagePartType.TOOLCALL
                and part.tool_call
                and part.tool_call.task_definition.name == "final_result"
            ):
                args = part.tool_call.carguments_json or {}
                content_arg = args.get("content", "")
                if (
                    isinstance(content_arg, dict)
                    and content_arg.get("_type") == "GenericContent"
                    and "pk" in content_arg
                ):
                    try:
                        from server.models.content import GenericContent

                        content_arg = GenericContent.objects.get(
                            pk=content_arg["pk"]
                        ).get()
                    except Exception:  # pylint: disable=broad-exception-caught
                        pass
                text += str(content_arg)
        return text
    if isinstance(result, str):
        return result
    if isinstance(result, dict) and result.get("content") is not None:
        return str(result["content"])
    return ""


def _resolve_message(value: Any) -> Message | None:
    """Resolve a Message instance / pk / ``{"_type": "Message", "pk"}`` ref."""
    if isinstance(value, Message):
        return value
    if isinstance(value, int):
        return Message.objects.filter(pk=value).first()
    if isinstance(value, dict) and value.get("pk") is not None:
        return Message.objects.filter(pk=value["pk"]).first()
    return None


def ingest_reflection_result(
    _session: Session,
    anchor_message: Any = None,
    reflection_result: Any = None,
    **kwargs: Any,
) -> Message | None:
    """Insert the reflection report after ``anchor_message``.

    Dispatched by :func:`reflect_session` in the observed session once the
    fork's ``process_turn`` resolves. The report is written as a
    ``role=INFO`` / ``message_type=REFLECTION`` message whose plain text comes
    from the fork's ``final_result`` (auto-awaited via ``reflection_result``).

    Inserted *after* the anchor means mid-chain: any message that arrived while
    the reflection ran (e.g. the user resumed the session) is repointed to
    follow the report, so the ``prev_message`` chain stays a single line.
    """
    report_text = _extract_report_text(reflection_result).strip()
    if not report_text:
        return None

    anchor = _resolve_message(anchor_message) or _session.get_last_message()
    # Capture the anchor's current successor *before* creating the report, so
    # the anchor's next_messages does not yet include it.
    successor = (
        anchor.next_messages.order_by("pk").first() if anchor is not None else None
    )

    sv = _session.get_version_model()
    message = Message.objects.create(
        role=MessageRole.INFO,
        message_type=MessageType.REFLECTION,
        session=sv.session,
        session_version=sv,
        prev_message=anchor,
    )
    message.add_part(
        type=MessagePartType.MESSAGE,
        content_type=MessageContentType.TEXT,
        content="Reflection report:\n\n" + report_text,
    )

    # Relink the old successor so the chain does not fork (same as the
    # compaction marker insertion).
    if successor is not None and successor.pk != message.pk:
        successor.prev_message = message
        successor.save()

    # Two-phase write (see Message.save): publish only now parts exist.
    message.publish("create")
    return message
