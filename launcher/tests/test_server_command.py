import pytest
import os
from unittest.mock import MagicMock
from launcher.management.commands.server import Command

# By marking this with pytest.mark.django_db, we get access to the Django database
# and settings, even though this specific test doesn't use the DB directly.
# It's good practice for most Django-related tests.
@pytest.mark.django_db
def test_read_local_config_success():
    """
    Tests that _read_local_config correctly parses a valid config file.
    """
    # 1. Arrange: Create a temporary fake config file
    config_content = """
# This is a comment
LISTEN_ADDRESS = "127.0.0.1"
LISTEN_PORT = '8888' # A port number as a string
SECRET_KEY = "a-secret-key"

# An empty line above
INVALID_LINE_NO_EQUALS
"""
    # Use a temporary directory provided by pytest's tmp_path fixture
    # This is safer and cleaner than creating files manually.
    fake_config_path = "test_settings_local.py"
    with open(fake_config_path, "w") as f:
        f.write(config_content)

    # Instantiate the command
    command = Command()
    command.stdout = MagicMock() # Mock stdout to prevent printing during tests
    command.style = MagicMock()

    try:
        # 2. Act: Call the method we want to test
        parsed_config = command._read_local_config(fake_config_path)

        # 3. Assert: Check if the output is what we expect
        assert parsed_config is not None
        assert isinstance(parsed_config, dict)
        assert len(parsed_config) == 3  # Should ignore comments, empty lines, and invalid lines
        assert parsed_config["LISTEN_ADDRESS"] == "127.0.0.1"
        assert parsed_config["LISTEN_PORT"] == "8888"
        assert parsed_config["SECRET_KEY"] == "a-secret-key"
        assert "INVALID_LINE_NO_EQUALS" not in parsed_config

    finally:
        # 4. Cleanup: Remove the temporary file
        if os.path.exists(fake_config_path):
            os.remove(fake_config_path)

