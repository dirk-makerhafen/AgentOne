def test_write_local_config_success(tmp_path):
    """
    Tests that _write_local_config correctly writes configuration to a file.
    """
    # 1. Arrange
    config_data = {
        "LISTEN_ADDRESS": "127.0.0.1",
        "LISTEN_PORT": "8001",
        "SECRET_KEY": "my-test-secret"
    }
    test_config_path = tmp_path / "test_settings_local_output.py"

    command = Command()
    command.stdout = MagicMock()
    command.style = MagicMock()

    # 2. Act
    command._write_local_config(str(test_config_path), config_data)

    # 3. Assert
    assert test_config_path.exists()
    content = test_config_path.read_text()

    expected_content_lines = [
        "# This file is automatically generated by 'manage.py server setup'.",
        "# Do not edit it manually unless you know what you are doing.",
        "",
        "LISTEN_ADDRESS = '127.0.0.1'",
        "LISTEN_PORT = '8001'",
        "SECRET_KEY = 'my-test-secret'",
        "" # fs_write implicitly adds a newline at the end if the last line of content has one
    ]
    expected_content = "\n".join(expected_content_lines)

    assert content == expected_content
    command.stdout.write.assert_called_with(f"\nWriting configuration to {test_config_path}...")
